/** Resolve one locale-owned label and its named placeholders.
 * @param locale - Selected interface language.
 * @param key - Dictionary key.
 * @param values - Values substituted into the localized label.
 * @returns Localized product text.
 */
export function translate(locale: Locale, key: CopyKey, values: Record<string, string | number> = {}): string {
  return (locale === 'zh' ? zh[key] : en[key]).replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token))
}

